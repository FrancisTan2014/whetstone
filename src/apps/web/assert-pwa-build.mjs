// Build-time assertion (#438): after `vite build`, verify the PWA artifacts the installable app needs
// were actually emitted into `dist` — the generated manifest, the Workbox service worker, and the
// committed icons. The SW/manifest are generated (not hand-written), so this is the deterministic gate
// that a config regression can't silently drop them. Skipped when the PWA is intentionally disabled
// (the screenshot harness builds with WHETSTONE_DISABLE_PWA=true).
import { access } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

if (process.env.WHETSTONE_DISABLE_PWA === "true") {
  console.log("assert-pwa-build: skipped (WHETSTONE_DISABLE_PWA=true).");
  process.exit(0);
}

const dist = path.join(path.dirname(fileURLToPath(import.meta.url)), "dist");
const required = [
  "manifest.webmanifest",
  "sw.js",
  "icon-192.png",
  "icon-512.png",
  "icon-512-maskable.png",
  "icon-180.png"
];

const missing = [];
for (const name of required) {
  try {
    await access(path.join(dist, name));
  } catch {
    missing.push(name);
  }
}

if (missing.length > 0) {
  console.error(
    `assert-pwa-build: dist is missing PWA artifact(s): ${missing.join(", ")}.\n` +
      "The manifest/SW are generated by vite-plugin-pwa; check src/apps/web/vite.config.ts and public/."
  );
  process.exit(1);
}

console.log(`assert-pwa-build: OK — dist has ${required.join(", ")}.`);
